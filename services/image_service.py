class ImageService:

    def __init__(self):

        self.files = []

    # =====================================================
    # ADD FILES
    # =====================================================

    def add_files(self, files):

        self.files = list(files)

    # =====================================================
    # GET FILES
    # =====================================================

    def get_files(self):

        return self.files

    # =====================================================
    # CLEAR FILES
    # =====================================================

    def clear_files(self):

        self.files.clear()


# =========================================================
# GLOBAL INSTANCE
# =========================================================

image_service = ImageService()